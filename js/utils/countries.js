// Helper to look up country details with guaranteed real national flag
export function getCountryFlag(codeOrName) {
  if (!codeOrName) return COUNTRY_MAP['ENG'];
  const key = String(codeOrName).toUpperCase().trim();
  if (COUNTRY_MAP[key]) return COUNTRY_MAP[key];

  // Fallback for custom code
  const fallbackIso = key.length === 2 ? key.toLowerCase() : 'un';
  return {
    code: key,
    iso: fallbackIso,
    name: key,
    flag: '🌐',
    flagUrl: `https://flagcdn.com/w40/${fallbackIso}.png`,
    flagSvg: `https://flagcdn.com/${fallbackIso}.svg`,
    flagHtml: `<img src="https://flagcdn.com/w40/${fallbackIso}.png" class="national-flag-img" alt="${key}" onerror="this.style.display='none'" loading="lazy" />`,
    flagHtmlLg: `<img src="https://flagcdn.com/w40/${fallbackIso}.png" class="national-flag-img-lg" alt="${key}" onerror="this.style.display='none'" loading="lazy" />`
  };
}

// Helper to render flag element directly
export function renderFlag(codeOrName, extraClass = '') {
  const nat = getCountryFlag(codeOrName);
  return `<img src="${nat.flagUrl}" class="national-flag-img ${extraClass}" alt="${nat.name}" title="${nat.name} (${nat.code})" loading="lazy" />`;
}

// Helper to generate <option> tags sorted A-Z for select dropdowns
export function renderCountryOptions(selectedCode = 'ENG') {
  const normSelected = String(selectedCode).toUpperCase().trim();
  return COUNTRIES.map(c => `
    <option value="${c.code}" ${c.code === normSelected || c.name.toUpperCase() === normSelected ? 'selected' : ''}>
      ${c.name} (${c.code})
    </option>
  `).join('');
}
